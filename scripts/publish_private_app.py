"""Publish the dashboard and its prepared data to a PRIVATE Git repository for hosting.

The source data is licensed for local use only, so prepared data must never be pushed to
a public repository. This script copies the app code and the data files the dashboard
reads into a clone of a private repository and pushes one commit. Files that exist in the
private repository but not locally (for example static model artifacts when this runs in
CI, which only rebuilds current data) are kept.

Usage:
    python scripts/publish_private_app.py --remote https://github.com/<you>/<private-repo>.git
    python scripts/publish_private_app.py --dry-run

The remote can also come from the ``DEPLOY_REMOTE`` environment variable (used in CI,
where it carries an access token and is therefore never printed).
"""

import argparse
import json
import logging
import os
import re
import shutil
import subprocess
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

from pl_analytics.config import get_settings

ROOT = Path(__file__).resolve().parents[1]
# Code is replaced wholesale on every publish.
CODE = ("app", "src", "reports/model_cards", ".streamlit/config.toml", "pyproject.toml")
# Data the dashboard reads, relative to the data and artifact directories.
PROCESSED = ("m4/*", "advanced/*", "fpl/*")
ARTIFACTS = (
    "dashboard/*",
    "m5/*.json",
    "m5/*.parquet",
    "m5/*.joblib",
    "m6/evaluation.json",
    "m6/selection.json",
    "m6/final/predictions.parquet",
    "m7/evaluation.json",
    "m7/selection.json",
    "m7/classifiers.joblib",
    "m7/predictions.parquet",
    "m7/statistical_benchmarks/latest_origin_models.joblib",
    "market/*",
)
README = """# Private deployment copy

Generated by `scripts/publish_private_app.py`. It contains prepared data that is licensed
for local use only: keep this repository private and do not edit it by hand.
"""


def _git(*arguments: str, cwd: Path, quiet: bool = False) -> str:
    result = subprocess.run(
        ["git", *arguments], cwd=cwd, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        # Never echo arguments or output: the remote may embed an access token.
        raise RuntimeError(f"git {arguments[0]} failed" + ("" if quiet else f": {result.stderr}"))
    return result.stdout.strip()


def _repository(remote: str) -> str | None:
    found = re.search(r"github\.com[:/]+([^/]+)/([^/]+?)(?:\.git)?/?$", remote)
    return f"{found.group(1)}/{found.group(2)}" if found else None


def _is_public(remote: str) -> bool:
    """True when GitHub serves the repository without credentials."""
    name = _repository(remote)
    if name is None:
        return False
    try:
        with urllib.request.urlopen(f"https://api.github.com/repos/{name}", timeout=15) as reply:
            return reply.status == 200
    except urllib.error.HTTPError:
        return False
    except urllib.error.URLError as error:
        raise RuntimeError("Could not check whether the repository is private") from error


def _copy_matches(base: Path, patterns: tuple[str, ...], destination: Path) -> int:
    copied = 0
    for pattern in patterns:
        for source in sorted(base.glob(pattern)):
            if source.is_file():
                target = destination / source.relative_to(base)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, target)
                copied += 1
    return copied


def stage(target: Path, data_dir: Path, artifact_dir: Path) -> dict:
    """Overlay code and whatever prepared data exists locally onto ``target``."""
    for item in CODE:
        source, destination = ROOT / item, target / item
        if destination.is_dir():
            shutil.rmtree(destination)
        destination.parent.mkdir(parents=True, exist_ok=True)
        if source.is_dir():
            shutil.copytree(source, destination, ignore=shutil.ignore_patterns("__pycache__"))
        else:
            shutil.copy2(source, destination)
    # Streamlit Community Cloud installs from this file: the package and its dependencies.
    (target / "requirements.txt").write_text(".\n", encoding="utf-8")
    (target / "README.md").write_text(README, encoding="utf-8")
    (target / ".gitignore").write_text("__pycache__/\n*.pyc\ndata/user/\n", encoding="utf-8")
    counts = {
        "processed": _copy_matches(data_dir / "processed", PROCESSED, target / "data/processed"),
        "artifacts": _copy_matches(artifact_dir, ARTIFACTS, target / "artifacts"),
    }
    catalog = artifact_dir / "dashboard/live_catalog.json"
    if catalog.exists():
        # Only the snapshot the catalog points at is needed; older ones are removed.
        paths = json.loads(catalog.read_text(encoding="utf-8")).get("paths", {})
        snapshots = target / "artifacts/live/snapshots"
        if snapshots.exists():
            shutil.rmtree(snapshots)
        for relative in paths.values():
            source = artifact_dir / relative
            destination = target / "artifacts" / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
            counts["artifacts"] += 1
    return counts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--remote", default=os.environ.get("DEPLOY_REMOTE"))
    parser.add_argument("--branch", default="main")
    parser.add_argument("--dry-run", action="store_true", help="Stage files without pushing")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    settings = get_settings()
    with tempfile.TemporaryDirectory() as temporary:
        target = Path(temporary) / "deploy"
        if args.dry_run:
            target.mkdir()
        else:
            if not args.remote:
                raise SystemExit("Give --remote or set DEPLOY_REMOTE")
            origin = _git("remote", "get-url", "origin", cwd=ROOT)
            if _repository(args.remote) == _repository(origin):
                raise SystemExit("Refusing to publish data to the source repository")
            if _is_public(args.remote):
                raise SystemExit("Refusing to publish: the target repository is public")
            _git("clone", "--quiet", args.remote, str(target), cwd=ROOT, quiet=True)
            branches = _git("branch", "--list", "--remotes", cwd=target)
            if f"origin/{args.branch}" in branches:
                _git("checkout", "--quiet", args.branch, cwd=target)
            else:
                _git("checkout", "--quiet", "--orphan", args.branch, cwd=target)
        counts = stage(target, settings.data_dir, settings.artifact_dir)
        size = sum(file.stat().st_size for file in target.rglob("*") if file.is_file())
        logging.info(
            "Staged %d processed and %d artifact files, %.1f MB in total",
            counts["processed"],
            counts["artifacts"],
            size / 1e6,
        )
        if args.dry_run:
            return
        _git("add", "--all", cwd=target)
        if not _git("status", "--porcelain", cwd=target):
            logging.info("Nothing changed; the private repository is already up to date")
            return
        source = _git("rev-parse", "--short", "HEAD", cwd=ROOT)
        _git(
            "-c",
            "user.name=analytics-lab-publisher",
            "-c",
            "user.email=publisher@users.noreply.github.com",
            "commit",
            "--quiet",
            "-m",
            f"Publish app and prepared data from {source}",
            cwd=target,
        )
        _git("push", "--quiet", "origin", f"HEAD:{args.branch}", cwd=target, quiet=True)
        logging.info("Published to %s (%s)", _repository(args.remote) or "the remote", args.branch)


if __name__ == "__main__":
    main()
